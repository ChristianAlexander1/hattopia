function load(url) {
  return new Promise((resolve) => {
    const im = new Image();
    im.onload = () => resolve(im);
    im.onerror = () => resolve(null);
    im.src = url;
  });
}

export async function loadAssets(onProgress) {
  const jobs = [];
  let done = 0;
  const total = 10; // atlas index, 2 block pages, 1 seed page, flora, ui, player, wrench, gems, backdrop
  const tick = () => { done++; if (onProgress) onProgress(done, total); };
  // Load tile atlases (replaces 250+ individual tile requests)
  jobs.push((async () => {
    const idx = await (await fetch('img/atlas/index.json')).json();
    tick();
    const atlases = {};
    const pages = new Set();
    for (const e of Object.values(idx.blocks)) pages.add(e.page);
    for (const e of Object.values(idx.seeds)) pages.add(e.page);
    await Promise.all([...pages].map(p =>
      load(`img/atlas/${p}.png`).then(im => { atlases[p] = im; tick(); })
    ));
    // Slice blocks
    for (const [key, e] of Object.entries(idx.blocks)) {
      const c = document.createElement('canvas');
      c.width = c.height = 32;
      c.getContext('2d').drawImage(atlases[e.page], e.x, e.y, 32, 32, 0, 0, 32, 32);
      imgs.tiles[key] = c;
    }
    // Slice seeds (for inventory icons via canvas)
    imgs.seedAtlas = { atlases, index: idx.seeds };
  })());
  const batch = (entries, store) => {
    const keys = Object.entries(entries);
    return Promise.all(keys.map(([k, f]) =>
      load('img/' + f).then((im) => { store[k] = im; })
    )).then(tick);
  };
  jobs.push(batch(FLORA_FILES, imgs.flora));
  jobs.push(batch(UI_FILES, imgs.ui));
  jobs.push(Promise.all(PLAYER_FRAMES.map(n =>
    load('img/player/' + n + '.png').then((im) => { imgs.player[n] = im; })
  )).then(tick));
  jobs.push(load('img/icons/wrench.png').then((im) => { imgs.wrench = im; tick(); }));
  jobs.push(load('img/gems/gem_red.png').then((im) => { imgs.gem = im; tick(); }));
  // floating gem drop sprites
  jobs.push(Promise.all(['yellow', 'red', 'purple', 'green', 'black'].map(c =>
    load(`img/gems/gem_${c}.png`).then((im) => { imgs['gem_' + c] = im; })
  )).then(tick));
  jobs.push(load('img/backdrop.png').then((im) => { imgs.backdrop = im; tick(); }));
  await Promise.all(jobs);
}

// URL (string) for an inventory icon of an item id. Used by <img> tags.
export function itemIcon(id) {
  const it = itemById(id);
  if (!it) return '';
  if (id === 80) return 'img/icons/wrench.png';
  if (id === 81) return 'img/ui/fist.png';
  if (typeof SEED_FILES !== 'undefined' && SEED_FILES[id]) return SEED_FILES[id];
  if (it.kind === 'seed') return 'img/flora/seed.png';
  if (it.tile && TILE_FILES[it.tile]) return 'img/' + TILE_FILES[it.tile];
  return 'img/tiles/dirt.png';
}

// Canvas image for a foreground/background tile id.
export function tileImage(id) {
  const it = itemById(id);
  if (!it || !it.tile) return null;
  return imgs.tiles[it.tile] || null;
}

// Lock tile with access status: green keyhole if player has access
export function lockTileImage(id, hasAccess) {
  if (id === 50) return imgs.tiles[hasAccess ? 'obj_worldlock_access' : 'obj_worldlock'] || null;
  if (id === 51) return imgs.tiles[hasAccess ? 'obj_diamondlock_access' : 'obj_diamondlock'] || null;
  return tileImage(id);
}

export function itemDesc(id) {
  const it = itemById(id);
  if (!it) return '';
  const parts = [];
  parts.push({ block: 'Block', bg: 'Background', seed: 'Seed', lock: 'Lock', tool: 'Tool', deco: 'Decor' }[it.kind] || it.kind);
  if (it.rarity) parts.push(`Rarity ${it.rarity}`);
  if (it.kind === 'seed') {
    const tree = itemById(it.treeOf);
    parts.push(`Grows a ${tree ? tree.name : 'tree'}`);
  }
  if (it.kind === 'lock') parts.push('Place to claim a world');
  if (it.action === 'door') parts.push('Punch to travel to spawn (visitors); owners punch to break');
  if (it.kind === 'deco' && !it.action) parts.push('Decorative');
  if (id === 80) parts.push('Tap a player to see their info, trade, or manage access');
  if (id === 81) parts.push('Punch blocks from a distance');
  return parts.join(' · ');
}
